import axios from "axios";
import { useLocation } from "react-router-dom";

function Result() {

  const location = useLocation();

  const analysis =
    location.state?.analysis ||
    "No analysis available";

  const image =
    location.state?.image || null;
  const scanId =
    location.state?.scanId || null;

  const handleSaveLesson = async () => {
  try {

    if (!scanId) {
      alert("No lesson found");
      return;
    }

    await axios.put(
      `https://stemverseai1.onrender.com/api/ai/save-lesson/${scanId}`
    );

    alert("Lesson Saved Successfully ⭐");

  } catch (error) {

    console.error(error);

    alert("Failed to save lesson");

  }
};

  return (
    <div className="min-h-screen bg-black text-white px-4 sm:px-6 md:px-10 lg:px-20 py-8">

      {/* Header */}
      <div className="mb-10">

        <h1 className="text-3xl sm:text-4xl md:text-5xl font-bold text-cyan-400">
          STEM Analysis Result
        </h1>

        <p className="text-gray-400 mt-3 text-sm sm:text-base">
          AI-powered STEM explanation generated by Gemini.
        </p>

      </div>

      {/* Responsive Grid */}
      <div className="grid lg:grid-cols-2 gap-8">

        {/* Uploaded Image */}
        <div className="bg-zinc-900 border border-zinc-800 rounded-3xl p-6">

          <h2 className="text-2xl font-bold mb-6">
            Uploaded Image
          </h2>

          {image ? (
            <img
              src={image}
              alt="Uploaded"
              className="
                w-full
                rounded-2xl
                border
                border-cyan-500
                object-cover
                max-h-[500px]
              "
            />
          ) : (
            <div
              className="
                h-72
                flex
                items-center
                justify-center
                border
                border-zinc-700
                rounded-2xl
                text-gray-500
              "
            >
              No Image Found
            </div>
          )}

        </div>

        {/* AI Analysis */}
        <div className="bg-zinc-900 border border-zinc-800 rounded-3xl p-6">

          <h2 className="text-2xl font-bold mb-6">
            AI Analysis
          </h2>

          <div
            className="
              whitespace-pre-wrap
              leading-8
              text-gray-300
              text-sm
              sm:text-base
            "
          >
            {analysis}
          </div>

        </div>

      </div>

      {/* Learning Levels */}
      <div className="mt-10 bg-zinc-900 border border-zinc-800 rounded-3xl p-6">

        <h2 className="text-2xl font-bold mb-4">
          Learning Levels
        </h2>

        <div className="flex flex-wrap gap-4">

          <span className="bg-green-500 px-4 py-2 rounded-xl">
            Beginner
          </span>

          <span className="bg-yellow-500 px-4 py-2 rounded-xl text-black">
            Intermediate
          </span>

          <span className="bg-red-500 px-4 py-2 rounded-xl">
            Advanced
          </span>

        </div>

      </div>

      {/* Future Quiz Section */}
      <div className="mt-10 bg-zinc-900 border border-zinc-800 rounded-3xl p-6">

        <h2 className="text-2xl font-bold mb-4">
          AI Quiz (Coming Next)
        </h2>

        <p className="text-gray-400">
          Soon Gemini will automatically generate quizzes
          based on detected objects.
        </p>

      </div>

      {/* Buttons */}
      <div className="flex flex-wrap gap-4 mt-10">

        <button
          onClick={handleSaveLesson}
          className="
          bg-cyan-500
          hover:bg-cyan-600
          px-6
          py-3
          rounded-xl
          font-semibold
          "
        >
          ⭐ Save Lesson
        </button>

        <button
          className="
            bg-zinc-800
            hover:bg-zinc-700
            px-6
            py-3
            rounded-xl
            font-semibold
          "
        >
          Share Result
        </button>

        <button
          className="
          bg-cyan-500
          hover:bg-cyan-600
          px-6
          py-3
          rounded-xl
          font-semibold
          transition
          mt-6
          "
          >
          Generate Quiz
          </button>

      </div>

    </div>
  );
}

export default Result;
